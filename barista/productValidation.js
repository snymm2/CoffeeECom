'use strict'

const allowedFields = new Set([
    'sku',
    'name',
    'brand',
    'type',
    'category',
    'price',
    'discountPercent',
    'imageUrl',
    'ratingAvg',
    'ratingTotal',
    'stock',
    'isFeatured',
    'isActive',

    'coffeeType',
    'roastLevel',
    'grindSize',
    'origin',
    'weightGrams',
    'location',
    'process',
    'tastingNotes',
    'variant',
    'flavor',
    'volumeMl',
    'flavorProfile',

    'machineType',
    'powerWatts',
    'pressureBar',
    'capacityLiters',
    'operationMode',
    'brewingMethod',
    'capacityMl',
    'material',
    'heatingMethod',
    'grinderType',
    'capacityGrams',
    'grindSettings',
    'accessoryType',
    'drinkwareType',
    'insulated',
    'storageType',
    'airtight',
    'supplyType',
    'quantity',
    'compatibleWith',
    'giftSetType',
    'contents',
    'skillLevel',

    'merchandiseType',
    'sizes',
    'color'
]);

const requiredFields = [
    'sku',
    'name',
    'brand',
    'category',
    'price',
    'stock'
];

const allowedCategories = new Set([
    'coffee',
    'equipment',
    'merch'
]);

function validateProduct(product, { partial = false} = {}) {
    const errors = [];

    if (
        product === null ||
        typeof product !== 'object' ||
        Array.isArray(product)
    ) {
        return {
            valid: false,
            errors: ['Request body must be a JSON Object.']
        };
    }

    const fields = Object.keys(product);

    if (fields.length === 0) {
        errors.push("Request Body must not be empty.");
    }

    for (const field of fields) {
        if (!allowedFields.has(field)) {
            errors.push(`Unknnown or Unsupported Field: ${field}.`);
        }
    }

    if ("_id" in product || 'id' in product) {
        errors.push("Product IDS are generated by the server");
    }

    if (!partial) {
        for (const field of requiredFields) {
            if (!Object.prototype.hasOwnProperty.call(product, field)) {
                errors.push(`Missing required field: ${field}.`)
            }
        }
    }

    for (const field of ['sku', 'name', 'brand', 'type', 'imageUrl']) {
        if (field in product && (
            typeof product[field] !== 'string' || product[field].trim().length === 0
        )) {
            errors.push(`${field} must be a non-empty string.`);
        }
    }

    if ('category' in product && (
        typeof product.category !== 'string' || !allowedCategories.has(product.category)
    )) {
        errors.push("'category' must be coffee, equipment, or merch.");
    }

    if ('price' in product && (
        typeof product.price !== 'number' || !Number.isFinite(product.price) || product.price < 0
    )) {
        errors.push("'price' must be a non-negative number.");
    }

    if ('discountPercent' in product && (
        typeof product.discountPercent !== 'number' ||
        !Number.isFinite(product.discountPercent) ||
        product.discountPercent < 0 ||
        product.discountPercent > 1
    )) {
        errors.push("'discountPercent' must be between 0 and 1.");
    }

    if ('stock' in product && (
        !Number.isInteger(product.stock) ||
        product.stock < 0
    )) {
        errors.push("'stock' must be a non-negative integer.")
    }

    if (
        'ratingAvg' in product &&
        (
            typeof product.ratingAvg !== 'number' ||
            !Number.isFinite(product.ratingAvg) ||
            product.ratingAvg < 0 ||
            product.ratingAvg > 5
        )
    ) {
        errors.push('"ratingAvg" must be between 0 and 5.');
    }

    if (
        'ratingTotal' in product &&
        (
            !Number.isInteger(product.ratingTotal) ||
            product.ratingTotal < 0
        )
    ) {
        errors.push('"ratingTotal" must be a non-negative integer.');
    }

    for (const field of ['isFeatured', 'isActive', 'insulated', 'airtight']) {
        if (
            field in product &&
            typeof product[field] !== 'boolean'
        ) {
            errors.push(`"${field}" must be a boolean.`);
        }
    }

    // Validate other numeric product attributes.
    const nonNegativeNumberFields = [
        'weightGrams',
        'volumeMl',
        'powerWatts',
        'pressureBar',
        'capacityLiters',
        'capacityMl',
        'capacityGrams'
    ];

    for (const field of nonNegativeNumberFields) {
        if (
            field in product &&
            (
                typeof product[field] !== 'number' ||
                !Number.isFinite(product[field]) ||
                product[field] < 0
            )
        ) {
            errors.push(`"${field}" must be a non-negative number.`);
        }
    }

    if ('quantity' in product &&
        (!Number.isInteger(product.quantity) || product.quantity < 0)) {
        errors.push('"quantity" must be a non-negative integer.');
    }

    if (
        'grindSettings' in product &&
        (!Number.isInteger(product.grindSettings) ||
            product.grindSettings < 0)
    ) {
        errors.push('"grindSettings" must be a non-negative integer.');
    }

    // These attributes may be a string or an array of strings.
    for (const field of [
        'grindSize',
        'tastingNotes',
        'sizes',
        'compatibleWith',
        'contents'
    ]) {
        if (field in product) {
            const value = product[field];
            const validString = typeof value === 'string';
            const validStringArray =
                Array.isArray(value) &&
                value.every(item => typeof item === 'string');

            if (!validString && !validStringArray) {
                errors.push(
                    `"${field}" must be a string or an array of strings.`
                );
            }
        }
    }

    return {
        valid: errors.length === 0,
        errors
    };
}

module.exports = { validateProduct }